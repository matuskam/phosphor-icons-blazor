namespace PhosphorIcons.Blazor;

/// <summary>
/// The visual weight of a Phosphor icon.
/// </summary>
public enum IconWeight
{
    /// <summary>Lightest stroke.</summary>
    Thin,

    /// <summary>Light stroke.</summary>
    Light,

    /// <summary>Default medium stroke.</summary>
    Regular,

    /// <summary>Heavier stroke.</summary>
    Bold,

    /// <summary>Solid filled shape.</summary>
    Fill,

    /// <summary>Two-layer rendering with a primary filled shape and a secondary low-opacity layer.</summary>
    Duotone
}
